export function resolveLucideIconByName(name?: string): IconComponent | undefined {
  if (!name) return undefined;

  const normalized = normalizeIconName(name);
  const key = LUCIDE_ICON_ALIASES[normalized as keyof typeof LUCIDE_ICON_ALIASES] ?? normalized;

  return LUCIDE_ICON_REGISTRY[key as keyof typeof LUCIDE_ICON_REGISTRY] ?? Circle;
}
