function toKebabCase(name: string): string {
  return name
    .replace(/([A-Z])/g, (char, _match, offset) => (offset > 0 ? "-" : "") + char.toLowerCase())
    .replace(/([a-z])(\d)/g, "$1-$2")
    .toLowerCase();
}

function normalizeIconName(name: string): string {
  return name.includes("-") ? name.toLowerCase() : toKebabCase(name);
}

