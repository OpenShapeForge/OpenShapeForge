/**
 * Refreshes the design system's field components that the component catalog
 * takes its field part from: `config/design-system/figma-fields.json`.
 *
 * The input is the Battery design system's Figma manifest (`figma/manifest.json`
 * in the design-system repository), which is not part of this repository. The
 * output is checked in, so a build never needs the manifest; run this only when
 * Figma changed:
 *
 *   bun packages/compiler/scripts/figma-fields.ts --manifest <path>/figma/manifest.json
 *   bun packages/compiler/scripts/figma-fields.ts --manifest <path> --check   # fails when stale
 *
 * Names follow the design system's own generator (`figma/generate.ts`): a
 * component `field/single-line` is `FieldSingleLine`, a property `Label width`
 * is `labelWidth`. A second component with a name already taken is left out
 * and listed under `skipped`: YAML keeps choosing such a version with the
 * existing non-Figma prop until design gives it a name of its own.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

type Prop = { name: string; figmaKey: string; type: string; default?: unknown; options?: string[] };
type Component = { id: string; name: string; page: string; description: string; props: Prop[] };

export const FIGMA_FIELDS_PATH = join(import.meta.dir, "..", "config", "design-system", "figma-fields.json");

const words = (text: string) => text.replace(/([a-z0-9])([A-Z])/g, "$1 $2").split(/[^A-Za-z0-9]+/).filter(Boolean);
const camel = (text: string) =>
  words(text).map((word, index) => (index === 0 ? word.toLowerCase() : word[0]!.toUpperCase() + word.slice(1).toLowerCase())).join("");
const pascal = (text: string) => words(text).map((word) => word[0]!.toUpperCase() + word.slice(1)).join("");
const kebab = (text: string) => words(text).map((word) => word.toLowerCase()).join("-");

/** The design system generator's prop naming, collisions included. */
function propNames(props: Prop[]): Map<string, string> {
  const names = new Map<string, string>();
  const taken = new Map<string, Prop>();
  for (const prop of props) {
    let name = camel(prop.name) || "value";
    const other = taken.get(name);
    if (other) {
      const flag = prop.type === "BOOLEAN" ? prop : other.type === "BOOLEAN" ? other : null;
      if (flag) {
        const renamed = "show" + pascal(flag.name);
        if (flag === other) {
          names.set(other.figmaKey, renamed);
          taken.set(renamed, other);
          taken.delete(name);
        } else name = renamed;
      }
      while (taken.has(name)) name += "2";
    }
    names.set(prop.figmaKey, name);
    taken.set(name, prop);
  }
  return names;
}

/** The first paragraph of Figma's description: what the field is. Usage notes for designers stay in Figma. */
const summary = (description: string) => description.replace(/^AI usage instructions\s*/i, "").trim().split(/\n\s*\n/)[0]!.replace(/\s+/g, " ").trim();

export function figmaFields(manifest: { fileKey?: string; components: Component[] }) {
  const fields: Record<string, unknown> = {};
  const skipped: Array<{ figma: string; node: string; name: string; reason: string }> = [];
  const seen = new Map<string, number>();
  for (const component of manifest.components) {
    if (component.page !== "molecules / fields" || !component.name.startsWith("field/")) continue;
    const slug = kebab(component.name);
    const count = (seen.get(slug) ?? 0) + 1;
    seen.set(slug, count);
    if (count > 1) {
      skipped.push({ figma: component.name, node: component.id, name: pascal(`${slug}-${count}`),
        reason: "Figma has another component of this name; YAML chooses the version with the component's existing props." });
      continue;
    }
    const names = propNames(component.props);
    const props = Object.fromEntries(component.props.map((prop) => [names.get(prop.figmaKey)!, {
      figma: prop.name,
      type: prop.type,
      ...(prop.default !== undefined ? { default: prop.default } : {}),
      ...(prop.options ? { options: [...prop.options].sort((a, b) => a.localeCompare(b, "en", { numeric: true })) } : {}),
    }]));
    fields[pascal(slug)] = { figma: component.name, node: component.id, description: summary(component.description), props };
  }
  return {
    $comment: "Generated by packages/compiler/scripts/figma-fields.ts from the Battery design system's Figma manifest. Do not edit; run the script when Figma changes.",
    fileKey: manifest.fileKey ?? null,
    fields: Object.fromEntries(Object.entries(fields).sort(([a], [b]) => a.localeCompare(b))),
    skipped,
  };
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { manifest: { type: "string" }, check: { type: "boolean", default: false } } });
  if (!values.manifest) {
    console.error("usage: bun packages/compiler/scripts/figma-fields.ts --manifest <design-system>/figma/manifest.json [--check]");
    process.exit(2);
  }
  const text = `${JSON.stringify(figmaFields(JSON.parse(readFileSync(values.manifest, "utf8"))), null, 2)}\n`;
  if (values.check) {
    const current = readFileSync(FIGMA_FIELDS_PATH, "utf8");
    if (current !== text) {
      console.error(`${FIGMA_FIELDS_PATH} is stale; run without --check to refresh it.`);
      process.exit(1);
    }
    console.log("figma-fields.json matches the manifest.");
  } else {
    writeFileSync(FIGMA_FIELDS_PATH, text);
    console.log(`wrote ${FIGMA_FIELDS_PATH}`);
  }
}
